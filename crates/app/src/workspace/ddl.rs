use super::*;

pub(super) fn render_dbeaver_col_badge(dtype_str: &str) -> Div {
    let lower = dtype_str.to_lowercase();
    if lower.contains("json") {
        div()
            .w(px(20.0))
            .flex()
            .items_center()
            .justify_center()
            .text_size(px(10.5))
            .font_weight(FontWeight::BOLD)
            .text_color(rgb(0x38bdf8))
            .child("{ }")
    } else if lower.contains("varchar") || lower.contains("text") || lower.contains("char") {
        div()
            .w(px(20.0))
            .flex()
            .items_center()
            .justify_center()
            .text_size(px(9.0))
            .font_weight(FontWeight::BOLD)
            .text_color(rgb(0x4daafc))
            .child("A-Z")
    } else if lower.contains("int")
        || lower.contains("num")
        || lower.contains("float")
        || lower.contains("dec")
        || lower.contains("double")
    {
        div()
            .w(px(20.0))
            .flex()
            .items_center()
            .justify_center()
            .text_size(px(9.5))
            .font_weight(FontWeight::BOLD)
            .text_color(rgb(0xa78bfa))
            .child("123")
    } else if lower.contains("date") || lower.contains("time") {
        div()
            .w(px(20.0))
            .flex()
            .items_center()
            .justify_center()
            .text_size(px(9.5))
            .child("📅")
    } else if lower.contains("bool") {
        div()
            .w(px(20.0))
            .flex()
            .items_center()
            .justify_center()
            .text_size(px(9.5))
            .font_weight(FontWeight::BOLD)
            .text_color(rgb(0xf43f5e))
            .child("✓")
    } else if lower.contains("uuid") {
        div()
            .w(px(20.0))
            .flex()
            .items_center()
            .justify_center()
            .text_size(px(8.0))
            .font_weight(FontWeight::BOLD)
            .text_color(rgb(0xfbbf24))
            .child("UUID")
    } else {
        div()
            .w(px(20.0))
            .flex()
            .items_center()
            .justify_center()
            .text_size(px(9.0))
            .font_weight(FontWeight::BOLD)
            .text_color(rgb(0x4daafc))
            .child("A-Z")
    }
}
